#!/usr/bin/env python3
"""
judge.py — LLM-as-a-Judge scoring for aegis-kg-unified eval pipeline.

Scores each eval trial across 4 dimensions:
- cypher_quality: syntactic + semantic correctness
- retrieval_accuracy: result completeness vs expected
- answer_quality: LLM answer quality
- regulatory_reasoning: understanding of EU regulatory context

Usage:
    from judge import judge_task

    scores = judge_task(task, pipeline_result)
"""

import json
import re
import time
import requests
from typing import Optional

from aegis_eval.config import OLLAMA


SYSTEM_JUDGE = """You are an expert evaluator for regulatory compliance knowledge graph queries.

Evaluate the quality of the query generation and answer generation process.

You will receive:
- TASK: The original question
- GENERATED_CYPHER: The Cypher query generated by the model
- DATABASE_RESULT: The raw results from executing the Cypher query
- EXPECTED_CYPHER: The ground-truth Cypher query
- EXPECTED_RESULT: What we expected the query to return
- LLM_ANSWER: The natural language answer generated from the results

Score each dimension from 1-5:
1 = Poor / Incorrect
2 = Below average
3 = Adequate / Partially correct
4 = Good / Mostly correct
5 = Excellent / Fully correct

Return a JSON object with:
{
  "scores": {
    "cypher_quality": <int 1-5>,
    "retrieval_accuracy": <int 1-5>,
    "answer_quality": <int 1-5>,
    "regulatory_reasoning": <int 1-5>
  },
  "explanation": "<brief explanation of each score>"
}
"""

USER_JUDGE_TEMPLATE = """TASK: {task}

GENERATED_CYPHER: {generated_cypher}

DATABASE_RESULT:
{db_result}

EXPECTED_CYPHER: {expected_cypher}

EXPECTED_RESULT_ROWS: {expected_rows}

LLM_ANSWER: {llm_answer}

Score the quality. Return JSON only."""


def call_ollama(prompt: str, system: str = "") -> dict:
    url = f"{OLLAMA['base_url']}/api/generate"
    payload = {
        "model": OLLAMA["model"],
        "prompt": prompt,
        "system": system,
        "stream": False,
        "options": {
            "temperature": 0.1,
            "num_predict": 512
        }
    }
    start = time.time()
    try:
        resp = requests.post(url, json=payload, timeout=OLLAMA["timeout"])
        elapsed = (time.time() - start) * 1000
        if resp.status_code != 200:
            return {"error": f"HTTP {resp.status_code}", "raw": resp.text[:300], "latency_ms": elapsed}
        data = resp.json()
        return {
            "raw": data.get("response", ""),
            "latency_ms": elapsed,
            "tokens": {
                "prompt_eval_count": data.get("prompt_eval_count", 0),
                "eval_count": data.get("eval_count", 0)
            }
        }
    except Exception as e:
        return {"error": str(e), "raw": "", "latency_ms": time.time() - start}


def format_results_for_judge(results: list[dict]) -> str:
    """Format Neo4j results for judge prompt."""
    if not results:
        return "EMPTY RESULTS — no data returned"
    lines = []
    for row in results[:15]:
        line = ", ".join(f"{k}={repr(v)[:50]}" for k, v in row.items())
        lines.append(f"  {line}")
    result_text = "\n".join(lines)
    if len(results) > 15:
        result_text += f"\n  ... and {len(results) - 15} more rows"
    return result_text


def judge_task(task: dict, pipeline_result: dict) -> dict:
    """
    Judge a single eval trial.

    Args:
        task: Task dict from task_bank.yaml
        pipeline_result: {
            'cypher': str,
            'cypher_raw': str,
            'execution_success': bool,
            'result_count': int,
            'results': list[dict],
            'llm_answer': str,
            'execution_error': str or None
        }

    Returns:
        {
            'scores': {
                'cypher_quality': int,
                'retrieval_accuracy': int,
                'answer_quality': int,
                'regulatory_reasoning': int
            },
            'explanation': str,
            'latency_ms': float,
            'tokens': dict,
            'error': str or None
        }
    """
    generated_cypher = pipeline_result.get("cypher", "")
    db_results = pipeline_result.get("results", [])
    llm_answer = pipeline_result.get("llm_answer", "")
    expected_cypher = task.get("expected_cypher", "")
    expected = task.get("expected_result", {})

    db_result_text = format_results_for_judge(db_results)
    expected_rows = json.dumps(expected, indent=2, default=str)[:2000]

    user_prompt = USER_JUDGE_TEMPLATE.format(
        task=task.get("question", ""),
        generated_cypher=generated_cypher or "NONE",
        db_result=db_result_text,
        expected_cypher=expected_cypher,
        expected_rows=expected_rows,
        llm_answer=llm_answer or "NONE"
    )

    start = time.time()
    result = call_ollama(user_prompt, system=SYSTEM_JUDGE)
    judge_latency = (time.time() - start) * 1000

    if "error" in result:
        return {
            "scores": {"cypher_quality": 1, "retrieval_accuracy": 1, "answer_quality": 1, "regulatory_reasoning": 1},
            "explanation": f"Judge error: {result['error']}",
            "latency_ms": judge_latency,
            "tokens": {},
            "error": result["error"]
        }

    raw = result["raw"].strip()

    # Remove markdown code block wrappers
    raw = re.sub(r"^```json\s*", "", raw, flags=re.IGNORECASE)
    raw = re.sub(r"^```\s*", "", raw)
    raw = re.sub(r"\s*```$", "", raw)
    raw = raw.strip()

    try:
        parsed = json.loads(raw)
        scores = parsed.get("scores", {})
        raw_explanation = parsed.get("explanation", "")

        if isinstance(raw_explanation, dict):
            explanation = "; ".join(f"{k}: {v}" for k, v in raw_explanation.items())
        elif isinstance(raw_explanation, str):
            explanation = raw_explanation
        else:
            explanation = str(raw_explanation)

        def clamp(val, default=0):
            try:
                v = int(val)
                return max(1, min(5, v))
            except (ValueError, TypeError):
                return default

        return {
            "scores": {
                "cypher_quality": clamp(scores.get("cypher_quality"), 0),
                "retrieval_accuracy": clamp(scores.get("retrieval_accuracy"), 0),
                "answer_quality": clamp(scores.get("answer_quality"), 0),
                "regulatory_reasoning": clamp(scores.get("regulatory_reasoning"), 0)
            },
            "explanation": explanation,
            "latency_ms": judge_latency,
            "tokens": result.get("tokens", {}),
            "error": None
        }
    except json.JSONDecodeError as e:
        return {
            "scores": {"cypher_quality": 3, "retrieval_accuracy": 3, "answer_quality": 3, "regulatory_reasoning": 3},
            "explanation": f"Failed to parse judge JSON. Raw: {raw[:500]}",
            "latency_ms": judge_latency,
            "tokens": result.get("tokens", {}),
            "error": "JSON parse failed"
        }


